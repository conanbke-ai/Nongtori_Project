export function translate(
  language: Language,
  key: TranslationKey,
  values?: Record<string, string | number>,
) {
  const template = language === 'ko' ? ko[key] : translations[language][key] ?? ko[key];
  if (!values) return template;
  return template.replace(/\{([A-Za-z0-9_]+)\}/g, (match, name: string) => (
    values[name] === undefined ? match : String(values[name])
  ));
}

export function localeForLanguage(language: Language) {
  return language === 'vi' ? 'vi-VN' : language === 'th' ? 'th-TH' : language === 'zh-CN' ? 'zh-CN' : 'ko-KR';
}

export function asLanguage(value: unknown): Language {
  return typeof value === 'string' && languages.includes(value as Language) ? value as Language : 'ko';
}
